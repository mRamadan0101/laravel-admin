<?php

use Encore\Admin\AdminServiceProvider;
use Encore\Admin\Facades\Admin;
use Illuminate\Support\Arr;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;
use Orchestra\Testbench\BrowserKit\TestCase as BaseTestCase;

class TestCase extends BaseTestCase
{
    protected $baseUrl = 'http://localhost:8000';

    protected function getPackageProviders($app)
    {
        return [AdminServiceProvider::class];
    }

    protected function getPackageAliases($app)
    {
        return ['Admin' => Admin::class];
    }

    protected function defineEnvironment($app)
    {
        $this->registerAppAutoloader($app);

        $adminConfig = require __DIR__.'/config/admin.php';

        $config = $app['config'];

        $config->set('database.default', env('DB_CONNECTION', 'mysql'));
        $config->set('database.connections.mysql.host', env('MYSQL_HOST', 'localhost'));
        $config->set('database.connections.mysql.port', env('DB_PORT', env('MYSQL_PORT', 3306)));
        $config->set('database.connections.mysql.database', env('MYSQL_DATABASE', 'laravel_admin_test'));
        $config->set('database.connections.mysql.username', env('MYSQL_USER', 'root'));
        $config->set('database.connections.mysql.password', env('MYSQL_PASSWORD', ''));
        $config->set('app.key', 'base64:'.base64_encode('AckfSECXIvnK5r28GVIWUAxmbBSjTsmF'));
        $config->set('filesystems', require __DIR__.'/config/filesystems.php');
        $config->set('admin', $adminConfig);

        foreach (Arr::dot(Arr::get($adminConfig, 'auth'), 'auth.') as $key => $value) {
            $config->set($key, $value);
        }
    }

    protected function setUp(): void
    {
        parent::setUp();

        $this->artisan('vendor:publish', ['--provider' => AdminServiceProvider::class]);

        Schema::defaultStringLength(191);

        $this->artisan('admin:install');

        $this->migration(__DIR__.'/migrations/2016_11_22_093148_create_test_tables.php')->up();

        if (file_exists($routes = admin_path('routes.php'))) {
            require $routes;
        }

        require __DIR__.'/routes.php';
    }

    protected function tearDown(): void
    {
        $this->migration(__DIR__.'/../database/migrations/2016_01_04_173148_create_admin_tables.php')->down();

        $this->migration(__DIR__.'/migrations/2016_11_22_093148_create_test_tables.php')->down();

        DB::delete('delete from `migrations` where `migration` = ?', ['2016_01_04_173148_create_admin_tables']);

        parent::tearDown();
    }

    /**
     * @param string $path
     *
     * @return \Illuminate\Database\Migrations\Migration
     */
    protected function migration($path)
    {
        return require $path;
    }

    /**
     * Classes generated by admin:install live in the testbench skeleton's App namespace,
     * which is not part of composer's autoload map.
     */
    protected function registerAppAutoloader($app)
    {
        static $registered = false;

        if ($registered) {
            return;
        }

        $appPath = $app->path();

        spl_autoload_register(function ($class) use ($appPath) {
            if (strncmp($class, 'App\\', 4) !== 0) {
                return;
            }

            $file = $appPath.'/'.str_replace('\\', '/', substr($class, 4)).'.php';

            if (is_file($file)) {
                require $file;
            }
        });

        if (!class_exists('App\Http\Controllers\Controller')) {
            class_alias(\Illuminate\Routing\Controller::class, 'App\Http\Controllers\Controller');
        }

        $registered = true;
    }
}
